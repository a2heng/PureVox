mod tests {
  use super::*;

  #[test]
  fn english_lookup_falls_back_to_chinese() {
    set("en");
    assert_eq!(tr("网络"), "Network");
    assert_eq!(tr("这句没有译文"), "这句没有译文");
    set("zh");
    assert_eq!(tr("网络"), "网络");
  }
}
