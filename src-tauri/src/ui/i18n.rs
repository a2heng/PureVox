/// 当前语言（`zh` / `en`）。
pub fn current() -> &'static str {
  if EN.load(Relaxed) { "en" } else { "zh" }
}

/// 切语言。只认 `en`，其余一律中文。
pub fn set(lang: &str) {
  EN.store(lang == "en", Relaxed);
}

/// 中文 msgid → 当前语言；没有译文就原样返回。
pub fn tr(zh: &str) -> &str {
  if !EN.load(Relaxed) {
    return zh;
  }
  match table().get(zh) {
    Some(en) => en,
    None => zh,
  }
}

